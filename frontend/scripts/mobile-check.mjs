import {chromium,expect} from '@playwright/test';
import {unpackMultiple} from '@colyseus/msgpackr';
const browser=await chromium.launch({headless:true,channel:'chromium'});
try{
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
 const page=await context.newPage(),errors=[],moves=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('websocket',ws=>ws.on('framesent',({payload})=>{
  if(typeof payload==='string')return;
  try{const data=unpackMultiple(payload.subarray(1));if(data[0]==='move')moves.push(data[1]);}catch{}
 }));
 await page.goto(process.env.BASE_URL||'http://localhost:5173');
 await page.getByRole('button',{name:'Vào chùa',exact:true}).tap();
 await page.getByLabel('Tên của bạn').fill('Khách Cảm Ứng');
 await page.getByRole('button',{name:'Bắt đầu',exact:true}).tap();
 const stick=page.getByLabel('Cần di chuyển'),look=page.getByLabel('Vùng xoay camera');
 await expect(stick).toBeVisible();
 await page.waitForTimeout(1200);
 const cdp=await context.newCDPSession(page);
 const r=await stick.boundingBox(),l=await look.boundingBox();
 const finger={id:1,x:r.x+r.width/2,y:r.y+r.height/2};
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[finger]});
 finger.y-=35;
 await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[finger]});
 await expect.poll(()=>moves.some(m=>Math.hypot(m.dx,m.dz)>.5)).toBe(true);
 const moving=moves.at(-1),second={id:2,x:l.x+40,y:l.y+45};
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[finger,second]});
 second.x+=75;
 await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[finger,second]});
 await expect.poll(()=>Math.abs(moves.at(-1).rotationY-moving.rotationY)).toBeGreaterThan(.1);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
 await expect.poll(()=>Math.hypot(moves.at(-1).dx,moves.at(-1).dz)).toBe(0);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[finger]});
 await expect.poll(()=>Math.hypot(moves.at(-1).dx,moves.at(-1).dz)).toBeGreaterThan(.5);
 await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
 await expect.poll(()=>Math.hypot(moves.at(-1).dx,moves.at(-1).dz)).toBe(0);
 await page.screenshot({path:'test-results/mobile-game.png'});
 await page.getByRole('button',{name:'Mở chat',exact:true}).tap();
 await page.getByLabel('Tin nhắn',{exact:true}).tap();
 await expect(stick).toBeHidden();
 await page.getByLabel('Tin nhắn',{exact:true}).fill('Chào từ điện thoại');
 await page.getByRole('button',{name:'Gửi tin nhắn',exact:true}).tap();
 await page.getByRole('log').getByText('Chào từ điện thoại').waitFor();
 await page.getByRole('button',{name:'Ẩn',exact:true}).tap();
 await expect(stick).toBeVisible();
 await page.getByRole('button',{name:'Cài đặt',exact:true}).tap();
 await expect(stick).toBeHidden();
 await page.getByRole('button',{name:'Đóng',exact:true}).tap();
 await page.setViewportSize({width:844,height:390});
 await expect(stick).toBeVisible();
 await page.screenshot({path:'test-results/mobile-landscape.png'});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:/Quỳ xuống/}).tap();
 await page.getByRole('button',{name:/Đứng lên/}).waitFor();
 await page.getByRole('button',{name:'Cài đặt',exact:true}).tap();
 await page.getByRole('button',{name:'Rời chùa',exact:true}).tap();
 expect(errors).toEqual([]);
 console.log('Mobile passed: multitouch movement/camera, release stop, chat, modal pause, sit, portrait/landscape, leave.');
}finally{await browser.close();}
